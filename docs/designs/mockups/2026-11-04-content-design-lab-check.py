"""Browser checks for the standalone design prototype, not Flutter acceptance.
Requires Python Playwright and an available Chromium. No external requests.
"""
from pathlib import Path
import argparse
import hashlib
import json
import os
import shutil
from playwright.sync_api import sync_playwright

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("html", type=Path, help="Path to the standalone HTML prototype")
parser.add_argument("--output", type=Path, default=Path.cwd()/".worktrees/_artifacts/content-design-lab")
parser.add_argument("--browser", default=os.environ.get("CHROMIUM") or shutil.which("chromium") or shutil.which("chromium-browser"))
args = parser.parse_args()
html = args.html.resolve()
if not html.is_file():
    parser.error(f"HTML file not found: {html}")
if not args.browser:
    parser.error("Set --browser or CHROMIUM to an installed Chromium executable")
root = args.output.resolve()
root.mkdir(parents=True, exist_ok=True)
results=[]
def check(label, condition):
    if not condition: raise AssertionError(label)
    results.append(label)
with sync_playwright() as pw:
    browser=pw.chromium.launch(executable_path=args.browser,headless=True,args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':1000}, reduced_motion='reduce')
    errors=[];requests=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('request',lambda r:requests.append(r.url))
    # Managed Chromium blocks file:// navigation here; set_content tests the
    # same complete HTML bytes without a server or remote dependencies.
    page.set_content(html.read_text(),wait_until='load')
    check('Initial architecture tab',page.locator('#architecture').is_visible())
    page.locator('[data-node=ref]').click()
    check('Reference inspector', 'Portable Address' in page.locator('#inspectTitle').inner_text())
    page.screenshot(path=str(root/'architecture-preview.png'),full_page=True)
    page.locator('#tab-screens').click()
    check('Cover-first composition',page.locator('#mainPreview [data-act=open]').count()==2)
    page.locator('#mainPreview [data-act=open]').first.click()
    check('Cover opens shared media viewer',page.locator('#mainPreview .media-modal').count()==1)
    page.locator('#mainPreview .media-modal [data-act=next]').click()
    check('Media next page',page.locator('#mainPreview .media-modal .counter').inner_text()=='2 / 4')
    page.locator('#mainPreview .media-modal [data-act=closeViewer]').click()
    check('Return to Work',page.locator('#mainPreview .media-modal').count()==0)
    page.locator('#variantSelect').select_option('inline')
    page.locator('#mainPreview .phonebody [data-act=next]').click()
    check('Inline page navigation',page.locator('#mainPreview .phonebody .counter').inner_text()=='3 / 4')
    page.locator('#missingPage').check()
    check('Missing source position stays Page 3','Page 3 Unavailable' in page.locator('#mainPreview .art').inner_text())
    page.locator('#mainPreview [data-act=next]').first.click()
    check('Missing member does not renumber Page 4',page.locator('#mainPreview .counter').inner_text()=='4 / 4')
    page.locator('#missingPage').uncheck()
    page.locator('#typeSelect').select_option('single')
    check('Single-image Work has no page arrows',page.locator('#mainPreview .phonebody [data-act=next]').count()==0)
    page.locator('#typeSelect').select_option('ugoira')
    check('Ugoira is one media item',page.evaluate('count()')==1 and page.locator('#mainPreview .counter').inner_text()=='Ugoira · Animation')
    check('Ugoira has no Manga Series field', 'Manga Series' not in page.locator('#mainPreview .phonebody').inner_text())
    page.locator('#typeSelect').select_option('illust')
    page.locator('#unknownData').check()
    check('Unknown metrics omitted',page.locator('#mainPreview .metrics').count()==0)
    page.locator('#unknownData').uncheck()
    page.locator('#initialControls').select_option('hidden')
    page.locator('#variantSelect').select_option('viewer')
    check('New viewer starts Hidden',page.locator('#mainPreview .phone').evaluate("e=>e.classList.contains('no-controls')"))
    page.locator('#mainPreview .phone').focus();page.keyboard.press('ArrowRight')
    check('Page change does not reset visibility',page.evaluate('state.page')==1 and page.evaluate('state.controls') is False)
    page.locator('#mainPreview .art').click(position={'x':140,'y':180})
    check('User toggles controls',page.evaluate('state.controls') is True)
    page.locator('#mainPreview .phonebody [data-act=next]').click()
    check('Visible state survives next page',page.evaluate('state.controls') is True and page.evaluate('state.page')==2)
    page.locator('#mainPreview [data-act=details]').first.click()
    check('Details sheet opens',page.locator('#mainPreview .sheet').count()==1)
    page.locator('#mainPreview .sheetbody').evaluate('(e)=>e.scrollTop=900')
    page.locator('#mainPreview .sheet [data-act=related]').first.click()
    check('Related result opens another Work',page.evaluate('state.workId')>=220 and page.evaluate('state.details') is False)
    page.locator('#mainPreview .apphead [data-act=back]').first.click()
    check('Back restores original Work and sheet',page.evaluate('state.workId')==120 and page.evaluate('state.details') is True)
    check('Back restores details position',page.locator('#mainPreview .sheetbody').evaluate('e=>e.scrollTop')>0)
    page.locator('#resetScreen').click();page.locator('#initialControls').select_option('visible')
    page.locator('#mainPreview [data-act=saveWork]').click()
    check('Save Work does not save Pages',page.evaluate('savedWorks.size')==1 and page.evaluate('savedPages.size')==0)
    page.locator('#mainPreview [data-act=open]').first.click();page.locator('#mainPreview .media-modal [data-act=savePage]').click()
    check('Save Page is independent',page.evaluate('savedWorks.size')==1 and page.evaluate('savedPages.size')==1)
    page.locator('#screenSelect').select_option('series')
    page.locator('#mainPreview [data-act=work]').nth(2).click()
    check('Series opens the correct Work page count',page.evaluate('state.type')=='manga' and page.evaluate('count()')==8)
    page.locator('#mainPreview [data-act=back]').first.click()
    check('Nested Back returns to Series',page.evaluate('state.route')=='series')
    page.locator('#screenSelect').select_option('pool');page.locator('#mainPreview [data-act=page]').nth(7).click()
    check('Pool retains all eight member positions',page.locator('#mainPreview .media-modal .counter').inner_text()=='8 / 8')
    page.locator('#screenSelect').select_option('gallery');page.locator('#mainPreview [data-act=open]').first.click();page.locator('#mainPreview .media-modal [data-act=details]').first.click()
    check('Gallery metadata is source-appropriate','Artist Tools' not in page.locator('#mainPreview .sheet').inner_text() and 'Artist Tags' in page.locator('#mainPreview .sheet').inner_text())
    page.locator('#resetScreen').click();page.screenshot(path=str(root/'work-preview.png'),full_page=True)
    page.locator('#showCompare').click();check('Three variant comparisons',page.locator('#compareArea .phone').count()==3)
    page.screenshot(path=str(root/'work-comparison.png'),full_page=True)
    page.locator('#compareArea [data-pick=inline]').click();check('Comparison activates a variant',page.evaluate('state.variant')=='inline')
    page.locator('#tab-zoom').click()
    check('Square fits height at 2x',page.evaluate('zoomGeom.first')==2)
    page.locator('#zoomToggle').click();check('Zoom in',page.evaluate('zoomed') is True)
    page.locator('#zoomToggle').click();check('Second double-tap resets',page.evaluate('zoomed') is False)
    page.locator('#zoomShape').select_option('portrait');check('Portrait moderate step',abs(page.evaluate('zoomGeom.first')-1.35)<.001)
    page.locator('#zoomShape').select_option('landscape');check('Landscape zooms more than square',2<page.evaluate('zoomGeom.first')<4)
    page.locator('#zoomShape').select_option('panorama');check('Panorama candidate capped at 4x',page.evaluate('zoomGeom.first')==4)
    page.locator('#zoomPolicy').select_option('fit');check('Exact fit comparison reaches 8x',page.evaluate('zoomGeom.first')==8)
    page.locator('#zoomShape').select_option('comic');page.locator('#zoomToggle').click();page.locator('#zoomToggle').click()
    check('Comic reset keeps reading baseline',page.evaluate('zoomGeom.base')==3 and page.evaluate('zoomed') is False)
    page.locator('#zoomShape').select_option('square');page.locator('#zoomPolicy').select_option('bounded')
    page.screenshot(path=str(root/'zoom-preview.png'),full_page=True)
    page.locator('#tab-filters').click()
    page.locator('[data-scope-menu=header]').click();page.locator('.scope-menu [data-scope=Private]').click()
    check('Header scope switch', 'Private' in page.locator('[data-scope-menu=header]').inner_text())
    page.locator('[data-scope-menu=toolbar]').click();page.keyboard.press('Escape')
    check('Scope menu Escape dismissal',page.locator('.scope-menu').count()==0)
    check('No unverified All option',page.locator('[data-scope=All]').count()==0)
    page.screenshot(path=str(root/'filter-comparison.png'),full_page=True)
    for width in (1440,1024,390,320):
        page.set_viewport_size({'width':width,'height':900})
        for tab in ('architecture','screens','zoom','filters'):
            page.locator('#tab-'+tab).click()
            check(f'No horizontal page overflow: {width}px {tab}',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    page.set_viewport_size({'width':390,'height':844});page.locator('#tab-screens').click()
    page.screenshot(path=str(root/'mobile-preview.png'),full_page=True)
    check('No JavaScript exceptions',not errors)
    check('No network requests',not requests)
    browser.close()
report={'html':html.name,'html_sha256':hashlib.sha256(html.read_bytes()).hexdigest(),'checks':len(results),'passed':results,'javascript_errors':errors,'network_requests':requests,'limits':['Chromium set_content, not file URL due managed browser policy','Not Flutter, Android/Maestro, API or CORS acceptance','Zoom candidates and Work layout remain proposals']}
(root/'verification.json').write_text(json.dumps(report,indent=2))
print(json.dumps({'passed':len(results),'errors':errors,'networkRequests':len(requests)}))
