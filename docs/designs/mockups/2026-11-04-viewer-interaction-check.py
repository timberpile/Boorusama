from pathlib import Path
from PIL import Image
from playwright.sync_api import sync_playwright
import argparse
import json
import shutil
parser=argparse.ArgumentParser(description="Verify the standalone viewer interaction prototype.")
parser.add_argument("html",type=Path)
parser.add_argument("--artifacts",type=Path,default=Path(".worktrees/_artifacts/content-design-lab"))
args=parser.parse_args()
HTML=args.html.resolve()
ROOT=args.artifacts.resolve();ROOT.mkdir(parents=True,exist_ok=True)
FIX=ROOT/'fixtures';FIX.mkdir(exist_ok=True)
for n,w,h in [('square',500,500),('wide',1600,300),('tall',240,2400)]:
    im=Image.new('RGB',(w,h),(68,100,131));im.save(FIX/f'{n}.png')
(FIX/'corrupt.png').write_bytes(b'not an image')
checks=[]
def check(name,condition):
    assert condition,name
    checks.append(name)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=shutil.which("chromium"), args=["--no-sandbox"])
    page=browser.new_page(viewport={'width':1440,'height':1100})
    errors=[]; network=[]
    page.on('pageerror',lambda e: errors.append(str(e)))
    page.on('request',lambda r: network.append(r.url) if r.url.startswith(('https:','http:')) else None)
    page.set_content(HTML.read_text(), wait_until='load')
    page.wait_for_function('() => document.getElementById("picture").naturalWidth > 0')
    check('starts in Image View',page.evaluate('mode==="image"'))
    check('no image/work arrow buttons within phone',page.locator('#phone button').filter(has_text='Previous').count()==0 and page.locator('#phone button').filter(has_text='Next').count()==0)
    check('initial square centered',page.evaluate('Math.abs(parseFloat(picture.style.top)-(geometry().h-parseFloat(picture.style.height))/2)<1'))
    page.locator('#media').dblclick(position={'x':150,'y':210})
    check('double-click zooms without toggling Overview',page.evaluate('mode==="image" && transform(geometry()).s>1'))
    page.locator('#zoomButton').click()
    check('second double-tap resets to contain',page.evaluate('transform(geometry()).s===1'))
    page.locator('#toggleMode').click();check('overview accessible',page.evaluate('mode==="overview" && !document.getElementById("details").inert'))
    page.locator('#nextPage').click();check('overview preserved across page change',page.evaluate('mode==="overview" && pageIndex()===1'))
    page.locator('#nextWork').click();check('work skip does not traverse remaining pages',page.evaluate('workIndex===1 && pageIndex()===0'))
    page.locator('#prevWork').click();check('return restores previous Work page',page.evaluate('workIndex===0 && pageIndex()===1'))
    page.locator('#pageSelect').select_option('2');page.evaluate('movePage(1)')
    check('end-of-work swipe does not cross boundary',page.evaluate('workIndex===0 && pageIndex()===2'))
    page.locator('#toggleMode').click();page.locator('#workSelect').select_option('1');page.locator('#pageSelect').select_option('2')
    page.evaluate('const t=transform(geometry());t.cy=.65;draw()')
    before=page.evaluate('JSON.stringify(transform(geometry()))')
    page.locator('#toggleMode').click();check('comic Overview uses whole strip',page.evaluate('parseFloat(picture.style.height)<=geometry().h+1'))
    page.locator('#toggleMode').click();check('comic reading transform restored',page.evaluate('JSON.stringify(transform(geometry()))')==before)
    page.locator('#policy').select_option('classic');page.locator('#zoomButton').click();check('Classic auto-comic next tap resets to contain',page.evaluate('transform(geometry()).s===1'))
    page.locator('#workSelect').select_option('0');page.locator('#pageSelect').select_option('0')
    page.locator('#resetTransform').click();page.locator('#zoomButton').click();check('Classic square target is 3x',page.evaluate('transform(geometry()).s===3'))
    page.locator('#policy').select_option('candidate');page.locator('#zoomButton').click();check('candidate square uses other dimension',page.evaluate('Math.abs(transform(geometry()).s-geometry().q)<.001'))
    page.locator('#files').set_input_files([str(FIX/'square.png'),str(FIX/'wide.png'),str(FIX/'tall.png'),str(FIX/'corrupt.png')])
    page.wait_for_function('() => !document.getElementById("files").disabled')
    check('valid uploads make one local Work',page.evaluate('works[workIndex].local && works[workIndex].pages.length===3'))
    check('dimensions decoded correctly',page.evaluate('works[workIndex].pages[2].width===240 && works[workIndex].pages[2].height===2400'))
    check('invalid image reported', '1 skipped' in page.locator('#uploadStatus').inner_text())
    check('uploaded image replaces media source', page.locator('#picture').get_attribute('src').startswith('blob:'))
    check('no fake artist for local files', page.locator('#artist').is_hidden())
    page.locator('#pageSelect').select_option('2');page.locator('#toggleMode').click()
    page.screenshot(path=str(ROOT/'local-images-overview-preview.png'),full_page=True)
    page.locator('#files').set_input_files([str(FIX/'wide.png')]);page.wait_for_function('() => !document.getElementById("files").disabled')
    check('second selection creates another Work',page.evaluate('works.filter(w=>w.local).length===2'))
    page.locator('#prevWork').click();check('previous local Work selection retained',page.evaluate('pageIndex()===2'))
    page.locator('#clearLocal').click();check('clear releases local URLs and records',page.evaluate('localUrls.size===0 && works.length===3'))
    page.locator('#files').set_input_files({'name':'<b>unsafe</b>.png','mimeType':'image/png','buffer':(FIX/'square.png').read_bytes()})
    page.wait_for_function('() => !document.getElementById("files").disabled')
    check('filename treated as text',page.locator('#caption').inner_text()=='<b>unsafe</b>.png' and page.locator('#caption b').count()==0)
    page.locator('#clearLocal').click()
    for width in [320,390,768]:
        page.set_viewport_size({'width':width,'height':900})
        check(f'no document overflow at {width}px',page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'))
    page.set_viewport_size({'width':1440,'height':1100});page.locator('#workSelect').select_option('1');page.locator('#pageSelect').select_option('1');page.evaluate('setMode("image")')
    page.locator('#phone').screenshot(path=str(ROOT/'viewer-image-preview.png'))
    page.evaluate('setMode("overview")');page.wait_for_function('() => parseFloat(getComputedStyle(document.getElementById("details")).opacity)>.99')
    page.locator('#phone').screenshot(path=str(ROOT/'viewer-overview-preview.png'))
    page.evaluate('setMode("image");workIndex=0;positions.clear();transforms.clear();render()')
    page.wait_for_function('() => Math.abs(document.getElementById("media").getBoundingClientRect().height-geometry().h)<1')
    box=page.locator('#media').bounding_box()
    page.mouse.move(box['x']+box['width']*.75,box['y']+box['height']*.5)
    page.mouse.down();page.mouse.move(box['x']+box['width']*.25,box['y']+box['height']*.5,steps=12);page.mouse.up()
    check('one-pointer image swipe advances a page',page.evaluate('workIndex===0 && pageIndex()===1'))
    page.evaluate('setMode("overview")')
    page.wait_for_function('() => parseFloat(getComputedStyle(document.getElementById("details")).opacity)>.99')
    page.locator('#workMeta').scroll_into_view_if_needed()
    box=page.locator('#workMeta').bounding_box()
    page.mouse.move(box['x']+box['width']*.75,box['y']+35);page.mouse.down()
    page.mouse.move(box['x']+box['width']*.25,box['y']+35,steps=12);page.mouse.up()
    check('overview metadata swipe skips the Work',page.evaluate('workIndex===1 && pageIndex()===0'))
    page.evaluate('setMode("image")');page.locator('#media').focus()
    page.keyboard.press('Shift+ArrowLeft')
    check('keyboard Work skip restores page',page.evaluate('workIndex===0 && pageIndex()===1'))
    page.keyboard.press('ArrowLeft')
    check('keyboard image navigation independent',page.evaluate('workIndex===0 && pageIndex()===0'))
    page.evaluate('setMode("image")')
    page.locator('#media').click(position={'x':100,'y':100})
    page.wait_for_function('() => mode==="overview"')
    check('single image tap reveals Overview',page.evaluate('mode==="overview"'))
    page.evaluate('workIndex=0;positions.clear();transforms.clear();render();setMode("image")')
    page.locator('#files').set_input_files({'name':'not-allowed.svg','mimeType':'image/svg+xml','buffer':b'<svg xmlns="http://www.w3.org/2000/svg" width="10" height="10"/>'})
    page.wait_for_function('() => !document.getElementById("files").disabled')
    check('external-capable SVG input not admitted',page.evaluate('works.length===3 && localUrls.size===0'))
    page.locator('#toast').evaluate("e => e.classList.remove('show')")
    page.locator('#phone').screenshot(path=str(ROOT/'viewer-image-preview.png'))
    page.evaluate('setMode("overview")')
    page.wait_for_function('() => parseFloat(getComputedStyle(document.getElementById("details")).opacity)>.99')
    page.locator('#phone').screenshot(path=str(ROOT/'viewer-overview-preview.png'))
    check('no JavaScript errors',not errors);check('no network requests',not network)
    (ROOT/'verification.json').write_text(json.dumps({'passed':len(checks),'checks':checks,'errors':errors,'network':network},indent=2))
    print(json.dumps({'passed':len(checks),'checks':checks},indent=2))
    browser.close()
