"""Browser-only verification for the screenshot-aligned issue #176 mockup.

Run: python verify_prototype.py --chromium /usr/bin/chromium
Requires Playwright. This never tests Flutter or uses an API/account.
"""
import argparse
from pathlib import Path
from playwright.sync_api import sync_playwright

parser = argparse.ArgumentParser()
parser.add_argument('--chromium', default='/usr/bin/chromium')
args = parser.parse_args()
html = Path(__file__).with_name('index.html').read_text(encoding='utf-8')
checks = []
errors = []

def check(value, label):
    if not value:
        raise AssertionError(label)
    checks.append(label)

with sync_playwright() as pw:
    browser = pw.chromium.launch(executable_path=args.chromium, args=['--no-sandbox'])
    page = browser.new_page(viewport={'width': 1200, 'height': 950})
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.set_content(html)
    snapshot = lambda: page.evaluate('mockupSnapshot()')
    check(snapshot()['kind'] == 'pixiv' and snapshot()['mode'] == 'single', 'Pixiv default Single')
    check(page.locator('.single.immersive').count() == 1, 'Immersive shell')
    check(page.locator('.outer-nav').count() == 0, 'No extra outer-feed rail')
    check(page.locator('.single .bookmark-target').count() == 2, 'Two separate local Bookmark actions')
    check(page.locator('.single [data-action="bookmark-member"] .scope-mark .ico').count() == 1, 'Page scope badge')
    check(page.locator('.single [data-action="bookmark-group"] .scope-mark .ico').count() == 1, 'Work scope badge')
    check(page.locator('.single [data-action="bookmark-options"]').count() == 0, 'No split target chooser')
    check(page.locator('.single [data-action="favorite-member"]').count() == 0, 'No unwritable Pixiv Favorite heart')
    page.locator('.single [data-action="bookmark-group"]').click()
    check(page.locator('.popup .pop-target').inner_text().strip() == 'entire Work', 'Work picker has its own scope')
    page.locator('.popup [data-action="bookmark-folder"][data-folder="favorites"]').click()
    check(snapshot()['groupBookmarks'] == ['favorites'] and snapshot()['memberBookmarks'] == [], 'Work saved without Page')
    page.locator('.single [data-action="bookmark-member"]').click()
    check(page.locator('.popup .pop-target').inner_text().strip() == 'current Page', 'Page picker has its own scope')
    page.locator('.popup [data-action="bookmark-folder"][data-folder="review"]').click()
    check(snapshot()['groupBookmarks'] == ['favorites'] and snapshot()['memberBookmarks'] == ['review'], 'Page saved independently')
    check(snapshot()['style'] == 'direct', 'B+ is the default')
    check(page.locator('[data-action="toggle-direct"]').count() == 1, 'Direct destination button visible')
    page.locator('[data-action="toggle-direct"]').click()
    check(snapshot()['mode'] == 'timeline', 'B+ enters Timeline in one tap')
    check(page.locator('.t-header [data-action="bookmark-group"][data-bookmarked="true"]').count() == 1, 'Timeline reflects Work bookmark')
    page.locator('[data-action="toggle-direct"]').click()
    check(snapshot()['mode'] == 'single', 'B+ returns to Single in one tap')
    page.locator('#switchStyle').select_option('menu')
    page.locator('[data-action="view-menu"]').click()
    check(page.locator('.popup [data-action="pop-timeline"]').count() == 1, 'B menu')
    page.locator('.popup [data-action="pop-timeline"]').click()
    check(snapshot()['mode'] == 'timeline', 'Pixiv Timeline')
    check(page.locator('.tile').count() == 4, 'Pixiv 4 pages')
    check(page.locator('.tile .heart').count() == 0, 'No Pixiv page hearts')
    page.locator('.tile[data-id="w3"]').click()
    check(snapshot()['selected'] == 'w3' and snapshot()['mode'] == 'single', 'Pixiv page selection')
    check(snapshot()['memberBookmarks'] == [] and snapshot()['groupBookmarks'] == ['favorites'], 'Selection keeps group status and changes Page status')
    page.locator('[data-action="info"]').click()
    check(snapshot()['detail'] == 'detail', 'Detailed View')
    check(page.locator('.artist-line').count() == 1, 'Work metadata')
    check(page.locator('.single.detail .bookmark-target').count() == 2, 'Dual Bookmark controls in Detailed')
    page.locator('.detail-image').click()
    check(snapshot()['detail'] == 'immersive', 'Return to immersive')
    page.locator('.single [data-action="back"]').click()
    check(snapshot()['mode'] == 'timeline', 'Tile Back returns to Timeline')
    page.locator('#kind').select_option('pool')
    check(snapshot()['mode'] == 'timeline', 'Pool default Timeline')
    check(page.locator('.tile').count() == 68, 'Pool 68 fixtures')
    page.locator('.sort').click()
    check(page.locator('.popup [data-action="pop-source"]').count() == 1, 'Pool Ordered sort')
    page.locator('.popup [data-action="pop-newest"]').click()
    check(snapshot()['sequence'][0] == 'p68', 'Pool Latest sort')
    page.locator('#go-single').click()
    check(snapshot()['mode'] == 'single', 'Pool Single')
    check(page.locator('.single [data-action="sort"]').count() == 1 and 'Latest' in page.locator('.single [data-action="sort"]').inner_text(), 'Pool Single shares Timeline order selector')
    check(page.locator('.single .bookmark-target').count() == 2, 'Pool Single has Page and Pool Bookmarks')
    check(page.locator('.single [data-action="favorite-member"]').count() == 1, 'Danbooru Post Favorite is separate')
    page.locator('.single [data-action="bookmark-member"]').click()
    check(page.locator('.popup .pop-target').inner_text().strip() == 'current Post', 'Pool Post Bookmark target')
    page.locator('.popup [data-action="bookmark-folder"][data-folder="favorites"]').click()
    page.locator('.single [data-action="bookmark-group"]').click()
    check(page.locator('.popup .pop-target').inner_text().strip() == 'entire Pool', 'Pool Group Bookmark target')
    page.locator('.popup [data-action="bookmark-folder"][data-folder="review"]').click()
    check(snapshot()['memberBookmarks'] == ['favorites'] and snapshot()['groupBookmarks'] == ['review'], 'Pool Post and group states independent')
    page.locator('.single [data-action="favorite-member"]').click()
    check(snapshot()['favorite'] and snapshot()['groupBookmarks'] == ['review'], 'Remote Favorite does not affect local Bookmark')
    page.locator('#viewState').select_option('detail')
    check(page.locator('.detail-copy .group-box').count() == 0, 'No redundant Pool info card')
    check(page.locator('.detail-copy [data-action="post-group-link"]').count() == 1, 'Retain existing Pool link')
    page.locator('#kind').select_option('series')
    check(snapshot()['mode'] == 'single' and snapshot()['sequence'][0] == 'p1', 'Series default Single and source Ordered')
    page.locator('[data-action="info"]').click()
    check(page.locator('.detail-copy .group-box').count() == 0, 'No redundant Series context card')
    check(page.locator('.detail-copy [data-action="post-group-link"]').count() == 1, 'Series retains existing Post-to-Pool link')
    page.locator('.detail-copy [data-action="post-group-link"]').click()
    check(snapshot()['mode'] == 'timeline', 'Series link opens Timeline for description')
    page.locator('#kind').select_option('related')
    check(snapshot()['mode'] == 'single' and snapshot()['sort'] == 'oldest', 'Related default Single with Oldest order')
    check(page.locator('.single-overlay [data-action="sort"]').count() == 1, 'Related sort selector in upper header')
    check(page.locator('.single-position [data-action="sort"]').count() == 0, 'No sort beside page counter')
    check(page.locator('.single .bookmark-target').count() == 2, 'Related keeps both Bookmark scopes')
    page.locator('.single [data-action="sort"]').click()
    check(page.locator('.popup [data-action="pop-oldest"]').count() == 1 and page.locator('.popup [data-action="pop-newest"]').count() == 1, 'Single uses existing Oldest and Newest choices')
    check(page.locator('.popup [data-action="pop-custom"]').count() == 0 and page.locator('.editor').count() == 0, 'No custom reorder editor')
    page.locator('.popup [data-action="pop-newest"]').click()
    check(snapshot()['sequence'] == ['r2','r1'] and snapshot()['selected'] == 'r1', 'Sorting preserves selected Related member')
    check(page.locator('.page-counter').inner_text().strip() == '2 / 2', 'Member ordinal adjusts to sort')
    page.locator('.single [data-action="bookmark-group"]').click()
    check(page.locator('.popup .pop-target').inner_text().strip() == 'entire Related Group', 'Related Group bookmark target')
    page.locator('.popup [data-action="bookmark-folder"][data-folder="favorites"]').click()
    check(snapshot()['savedRelatedOrder'] == 'newest', 'Bookmarked Related group remembers visible Newest order')
    page.locator('[data-action="toggle-direct"]').click()
    check(snapshot()['mode'] == 'timeline' and 'Newest' in page.locator('.sort').inner_text(), 'Timeline uses same selected Related order')
    check(page.locator('.t-header [data-action="bookmark-group"][data-bookmarked="true"]').count() == 1, 'Related Group bookmark reflected in Timeline')
    check(page.locator('.app-nav').count() == 0, 'No invented Related bottom navigation')
    page.locator('.sort').click()
    page.locator('.popup [data-action="pop-oldest"]').click()
    check(snapshot()['sequence'] == ['r1','r2'] and snapshot()['savedRelatedOrder'] == 'oldest', 'Timeline selector updates saved bookmark order')
    page.locator('[data-action="toggle-direct"]').click()
    check(snapshot()['mode'] == 'single' and 'Oldest' in page.locator('.single-sort').inner_text(), 'Single reflects Timeline order change')
    page.locator('[data-action="info"]').click()
    check(page.locator('.single.detail .single-overlay [data-action="sort"]').count() == 1, 'Related sort selector in Detailed header')
    check(page.locator('.single.detail .single-position .page-counter').count() == 1, 'Detailed page counter is separate')
    check(page.locator('.single.detail .single-overlay [data-action="toggle-direct"]').count() == 1, 'B+ remains in Detailed header')
    page.locator('.single.detail [data-action="sort"]').click()
    page.locator('.popup [data-action="pop-newest"]').click()
    check(snapshot()['sort'] == 'newest' and snapshot()['savedRelatedOrder'] == 'newest', 'Detailed changes saved group sort')
    check(snapshot()['selected'] == 'r1', 'Detailed sorting preserves member')
    page.locator('.detail-image').click()
    page.locator('[data-action="single-more"]').click()
    page.locator('.popup [data-action="pop-order"]').click()
    check(page.locator('.popup [data-action="pop-oldest"]').count() == 1, 'Single overflow uses same standard order picker')
    page.locator('.popup [data-action="pop-oldest"]').click()
    check(snapshot()['sort'] == 'oldest', 'Overflow standard sort works')
    page.locator('#switchStyle').select_option('direct')
    page.locator('[data-action="toggle-direct"]').click()
    check(snapshot()['mode'] == 'timeline', 'B+ one-tap switch')
    page.locator('#switchStyle').select_option('overflow')
    check(page.locator('[data-action="view-menu"]').count() == 0, 'B− overflow-only')
    page.locator('[data-action="t-more"]').click()
    page.locator('.popup [data-action="pop-view"]').click()
    page.locator('.popup [data-action="pop-single"]').click()
    check(snapshot()['mode'] == 'single', 'B− can enter Single')
    for width in [360, 740, 1200]:
        page.set_viewport_size({'width': width, 'height': 850})
        check(page.evaluate('document.documentElement.scrollWidth <= innerWidth + 1'), f'No overflow at {width}px')
    check(not errors, f'No JS exceptions: {errors}')
    browser.close()
print(f'{len(checks)} browser checks passed')