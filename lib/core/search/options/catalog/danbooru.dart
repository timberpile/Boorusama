import '../search_option.dart';
import 'common.dart';

// Evidence: Danbooru PostQueryBuilder::METATAGS and help:cheatsheet.
// This is the search vocabulary, not the similarly named post-edit vocabulary.
List<SearchOption> danbooruOptions() {
  const prefix = SearchOptionNegation.prefix;
  const counts = [
    'comments',
    'deleted_comments',
    'active_comments',
    'notes',
    'deleted_notes',
    'active_notes',
    'flags',
    'children',
    'deleted_children',
    'active_children',
    'pools',
    'deleted_pools',
    'active_pools',
    'series_pools',
    'collection_pools',
    'appeals',
    'approvals',
    'replacements',
    'disapprovals',
    'tagcount',
    'gentags',
    'arttags',
    'chartags',
    'copytags',
    'metatags',
  ];
  const countAliases = {
    'comment_count': 'comments',
    'deleted_comment_count': 'deleted_comments',
    'active_comment_count': 'active_comments',
    'note_count': 'notes',
    'deleted_note_count': 'deleted_notes',
    'active_note_count': 'active_notes',
    'flag_count': 'flags',
    'child_count': 'children',
    'deleted_child_count': 'deleted_children',
    'active_child_count': 'active_children',
    'pool_count': 'pools',
    'deleted_pool_count': 'deleted_pools',
    'active_pool_count': 'active_pools',
    'series_pool_count': 'series_pools',
    'collection_pool_count': 'collection_pools',
    'appeal_count': 'appeals',
    'approval_count': 'approvals',
    'replacement_count': 'replacements',
    'disapproval_count': 'disapprovals',
  };
  return [
    const SearchOption(
      kind: SearchOptionKind.uploaded,
      key: 'age',
      input: SearchOptionInput.duration,
      allowRange: true,
      negation: SearchOptionNegation.comparison,
      choices: [
        SearchOptionChoice('older_month', '>1mo'),
        SearchOptionChoice('older_year', '>1y'),
        SearchOptionChoice('older_five_years', '>5y'),
      ],
    ),
    ratingOption(short: true),
    SearchOption(
      kind: SearchOptionKind.sort,
      key: 'order',
      input: SearchOptionInput.choice,
      choices: [
        const SearchOptionChoice('newest', 'id_desc'),
        const SearchOptionChoice('oldest', 'id_asc'),
        const SearchOptionChoice('highest_score', 'score'),
        const SearchOptionChoice('lowest_score', 'score_asc'),
        const SearchOptionChoice('most_favorites', 'favcount'),
        for (final value in <String>{
          'id',
          'favcount_asc',
          'md5',
          'md5_asc',
          'created_at',
          'created_at_asc',
          'change',
          'change_asc',
          'comment',
          'comment_asc',
          'comment_bumped',
          'comment_bumped_asc',
          'note',
          'note_asc',
          'artcomm',
          'artcomm_asc',
          'mpixels',
          'mpixels_asc',
          'portrait',
          'landscape',
          'filesize',
          'filesize_asc',
          'duration',
          'duration_asc',
          'upvotes',
          'upvotes_asc',
          'downvotes',
          'downvotes_asc',
          'disapproved',
          'disapproved_asc',
          'rank',
          'modqueue',
          'random',
          'custom',
          'none',
          for (final key in counts) ...[key, '${key}_asc'],
          ...countAliases.keys,
        })
          SearchOptionChoice(value, value),
      ],
    ),
    scoreOption(),
    numericOption('id', kind: SearchOptionKind.postId, negation: prefix),
    textOption(
      'user',
      kind: SearchOptionKind.uploader,
      description: 'user',
      negation: prefix,
    ),
    numericOption('date', input: SearchOptionInput.date, negation: prefix),
    for (final key in ['width', 'height'])
      numericOption(
        key,
        description: 'pixels',
        choices: pixelChoices,
        negation: prefix,
      ),
    numericOption(
      'mpixels',
      input: SearchOptionInput.decimal,
      negation: prefix,
      choices: const [
        SearchOptionChoice('≥ 2 MP', '>=2', literal: true),
        SearchOptionChoice('≥ 8 MP', '>=8', literal: true),
      ],
    ),
    numericOption(
      'ratio',
      input: SearchOptionInput.ratio,
      negation: prefix,
      choices: const [
        SearchOptionChoice('1:1', '1:1', literal: true),
        SearchOptionChoice('16:9', '16:9', literal: true),
        SearchOptionChoice('9:16', '9:16', literal: true),
      ],
    ),
    numericOption(
      'filesize',
      input: SearchOptionInput.filesize,
      negation: prefix,
      choices: const [
        SearchOptionChoice('< 1 MB', '<1mb', literal: true),
        SearchOptionChoice('≥ 10 MB', '>=10mb', literal: true),
      ],
    ),
    numericOption(
      'duration',
      input: SearchOptionInput.decimal,
      description: 'seconds',
      negation: prefix,
      choices: const [
        SearchOptionChoice('< 30 s', '<30', literal: true),
        SearchOptionChoice('≥ 60 s', '>=60', literal: true),
      ],
    ),
    enumOption('filetype', [
      'jpg',
      'png',
      'gif',
      'webp',
      'avif',
      'mp4',
      'webm',
      'swf',
      'zip',
    ], negation: prefix),
    enumOption(
      'status',
      [
        'active',
        'pending',
        'flagged',
        'deleted',
        'appealed',
        'modqueue',
        'any',
        'unmoderated',
        'banned',
      ],
      description: 'status',
      negation: prefix,
    ),
    for (final key in ['favcount', 'upvotes', 'downvotes', ...counts])
      numericOption(
        key,
        description: 'count',
        choices: countChoices,
        negation: prefix,
      ),
    for (final entry in countAliases.entries)
      numericOption(
        entry.key,
        label: entry.value,
        description: 'count',
        choices: countChoices,
        negation: prefix,
      ),
    for (final key in [
      'approver',
      'commenter',
      'comm',
      'noter',
      'noteupdater',
      'artcomm',
      'commentaryupdater',
      'appealer',
    ])
      textOption(key, description: 'user', choices: anyNone, negation: prefix),
    for (final key in ['flagger', 'upvote', 'downvote'])
      textOption(key, description: 'restricted_user', negation: prefix),
    textOption('fav', description: 'user', negation: prefix),
    for (final key in ['ordfav', 'ordvote'])
      textOption(key, description: 'ordered_user'),
    textOption(
      'disapproved',
      description: 'disapproved',
      choices: const [
        SearchOptionChoice('disinterest', 'disinterest'),
        SearchOptionChoice('breaks_rules', 'breaks_rules'),
        SearchOptionChoice('poor_quality', 'poor_quality'),
      ],
      negation: prefix,
    ),
    textOption(
      'pool',
      description: 'pool',
      choices: const [
        ...anyNone,
        SearchOptionChoice('series', 'series'),
        SearchOptionChoice('collection', 'collection'),
      ],
      negation: prefix,
    ),
    textOption('ordpool', description: 'ordered_pool'),
    textOption('favgroup', description: 'favgroup', negation: prefix),
    textOption('ordfavgroup', description: 'favgroup'),
    textOption('search', description: 'saved_search', negation: prefix),
    textOption(
      'source',
      description: 'source',
      choices: const [SearchOptionChoice('none', 'none')],
      negation: prefix,
    ),
    for (final key in ['md5', 'pixelhash'])
      textOption(key, description: 'hash', negation: prefix),
    for (final key in ['pixiv', 'pixiv_id', 'parent'])
      numericOption(key, description: 'id', choices: anyNone, negation: prefix),
    enumOption('child', ['any', 'none'], negation: prefix),
    enumOption('embedded', ['true', 'false'], negation: prefix),
    for (final key in ['note', 'comment', 'commentary'])
      textOption(
        key,
        choices: key == 'commentary'
            ? const [
                SearchOptionChoice('true', 'true'),
                SearchOptionChoice('false', 'false'),
                SearchOptionChoice('translated', 'translated'),
                SearchOptionChoice('untranslated', 'untranslated'),
              ]
            : const [],
        negation: prefix,
      ),
    textOption('exif', description: 'exif', negation: prefix),
    textOption('ai', description: 'ai', negation: prefix),
    textOption('unaliased', description: 'tag', negation: prefix),
    textOption('reacted', description: 'restricted_user', negation: prefix),
    enumOption('has', [
      'source',
      'parent',
      'children',
      'comments',
      'commentary',
      'notes',
      'pools',
      'appeals',
      'flags',
      'replacements',
    ], negation: prefix),
    enumOption('is', [
      'parent',
      'child',
      'general',
      'sensitive',
      'questionable',
      'explicit',
      'sfw',
      'nsfw',
      'active',
      'pending',
      'flagged',
      'deleted',
      'appealed',
      'modqueue',
      'jpg',
      'png',
      'gif',
      'mp4',
      'webm',
      'swf',
      'zip',
    ], negation: prefix),
    numericOption(
      'limit',
      ranges: false,
      description: 'limit',
      choices: const [
        SearchOptionChoice('20', '20', literal: true),
        SearchOptionChoice('100', '100', literal: true),
        SearchOptionChoice('200', '200', literal: true),
      ],
    ),
    numericOption(
      'random',
      ranges: false,
      description: 'random',
      choices: const [SearchOptionChoice('20', '20', literal: true)],
    ),
  ];
}
